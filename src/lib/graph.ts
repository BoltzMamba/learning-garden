/**
 * Unified knowledge-graph data (pure, built once at build time). Every view —
 * Article Graph, Topic Graph, the homepage preview and a note's local graph —
 * is a filter over this one structure (see graph-modes.ts).
 *
 * Nodes
 *   article   one per note file (overview or note); id `note:<file id>`
 *   topic     a controlled-vocabulary topic used by some note, or an ancestor of one
 *   question  a public question
 *
 * Edges — only relationships that exist in the content:
 *   links_to    article → article   a link written in the Markdown body (directed)
 *   related_to  article — article   frontmatter `related` (undirected)
 *   belongs_to  article → overview  frontmatter `series` (structural)
 *   tagged_with article → topic     frontmatter `tags`, resolved via the vocabulary
 *   parent_of   topic → topic       vocabulary `parent`
 *   asks_about  question → article  the question's `note` field
 *
 * Two articles that share a tag are NOT connected directly. A series' contents
 * list is generated by the page template, never parsed as body links.
 *
 * One logical note is one node, whatever its languages: relations come from
 * the Chinese source only (an English edition never adds or removes edges).
 * Paths here are language-neutral; pages localise them, article titles and
 * topic names with localizeGraph().
 */
import { extractNoteLinks, makeResolver } from './links.ts';
import { topicAncestors, type Vocabulary } from './topics.ts';
import type { GraphData, GraphEdge, GraphNode, EdgeKind } from './graph-modes.ts';

export * from './graph-modes.ts';

export interface GraphArticleInput {
  id: string;
  title: string;
  /** Per-language titles (Chinese source and English edition). */
  labels?: { zh: string; en: string };
  section: string;
  contentType: 'overview' | 'note';
  series?: string;
  related: readonly string[];
  /** Resolved topic ids. */
  topics: readonly string[];
  body: string;
}

export interface GraphQuestionInput {
  id: string;
  title: string;
  note?: string;
  public: boolean;
}

export const noteNodeId = (id: string) => `note:${id}`;
export const topicNodeId = (id: string) => `topic:${id}`;
export const questionNodeId = (id: string) => `q:${id}`;

export const DIRECTED: Readonly<Record<EdgeKind, boolean>> = {
  links_to: true,
  related_to: false,
  belongs_to: true,
  tagged_with: true,
  parent_of: true,
  asks_about: true,
};

export interface BuildResult extends GraphData {
  /** Body link targets that did not resolve to a note (for warnings). */
  unresolved: { from: string; target: string }[];
}

/** Key that makes one edge per (kind, pair); undirected kinds ignore order. */
export const edgeKey = (e: Pick<GraphEdge, 'kind' | 'source' | 'target'>) =>
  `${e.kind}|${DIRECTED[e.kind] ? `${e.source}>${e.target}` : [e.source, e.target].sort().join('~')}`;

export function buildGraph(
  articles: readonly GraphArticleInput[],
  questions: readonly GraphQuestionInput[] = [],
  vocab?: Vocabulary,
): BuildResult {
  const resolve = makeResolver(articles);
  const nodes = new Map<string, GraphNode>();
  const edges: GraphEdge[] = [];
  const seen = new Set<string>();
  const unresolved: BuildResult['unresolved'] = [];
  const ids = new Set(articles.map((a) => a.id));

  const addEdge = (source: string, target: string, kind: EdgeKind) => {
    if (source === target || !nodes.has(source) || !nodes.has(target)) return;
    const edge = { source, target, kind };
    const key = edgeKey(edge);
    if (seen.has(key)) return;
    seen.add(key);
    edges.push(edge);
  };

  for (const a of articles) {
    nodes.set(noteNodeId(a.id), {
      id: noteNodeId(a.id),
      kind: 'article',
      contentType: a.contentType,
      section: a.section,
      label: a.title,
      labels: a.labels,
      path: `/notes/${a.id}/`,
    });
  }

  // Topics actually used, plus their ancestors so parent_of chains are complete.
  const usedTopics = new Set<string>();
  for (const a of articles) {
    for (const t of a.topics) {
      usedTopics.add(t);
      if (vocab) topicAncestors(vocab, t).forEach((p) => usedTopics.add(p));
    }
  }
  for (const t of [...usedTopics].sort()) {
    const topic = vocab?.topics.get(t);
    nodes.set(topicNodeId(t), {
      id: topicNodeId(t),
      kind: 'topic',
      label: topic?.en ?? t,
      labels: topic ? { zh: topic.zh, en: topic.en } : undefined,
      path: `/notes/?tag=${encodeURIComponent(t)}`,
    });
  }

  for (const a of articles) {
    const from = noteNodeId(a.id);
    // Body links only: the series contents list is rendered by the template.
    const { targets, unresolved: missing } = extractNoteLinks(a.body, a.id, resolve);
    for (const t of targets) addEdge(from, noteNodeId(t), 'links_to');
    for (const target of missing) unresolved.push({ from: a.id, target });
    for (const r of a.related) if (ids.has(r)) addEdge(from, noteNodeId(r), 'related_to');
    if (a.series && ids.has(a.series)) addEdge(from, noteNodeId(a.series), 'belongs_to');
    for (const t of a.topics) addEdge(from, topicNodeId(t), 'tagged_with');
  }
  if (vocab) {
    for (const t of usedTopics) {
      const parent = vocab.topics.get(t)?.parent;
      if (parent) addEdge(topicNodeId(parent), topicNodeId(t), 'parent_of');
    }
  }

  for (const q of questions) {
    if (!q.public) continue;
    const id = questionNodeId(q.id);
    nodes.set(id, { id, kind: 'question', label: q.title, path: `/questions/#q-${q.id}` });
    if (q.note) addEdge(id, noteNodeId(q.note), 'asks_about');
  }

  return { nodes: [...nodes.values()], edges, unresolved };
}

/** Body-link backlinks/outlinks and manual relations of one note, as note ids. */
export function noteConnections(data: GraphData, noteId: string) {
  const self = noteNodeId(noteId);
  const strip = (id: string) => id.replace(/^note:/, '');
  const pick = (kind: EdgeKind, dir: 'in' | 'out' | 'any') =>
    data.edges
      .filter((e) => e.kind === kind && (dir === 'out' ? e.source === self : dir === 'in' ? e.target === self : e.source === self || e.target === self))
      .map((e) => strip(e.source === self ? e.target : e.source));
  return {
    outlinks: pick('links_to', 'out'),
    backlinks: pick('links_to', 'in'),
    related: pick('related_to', 'any'),
  };
}
